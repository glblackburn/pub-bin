#!/usr/bin/env bash
set -euET -o pipefail

script_name=$(basename $0)
script_dir=$(dirname $0)

################################################################################
# default values
################################################################################
ts=`date +%Y-%m-%d_%H%M%S`

################################################################################
# get command line options
################################################################################
ip=${1}

################################################################################
# main script logic
################################################################################
output_file=nslookup_${ip}_${ts}.txt

cat<<EOF
################################################################################
# Debug info
################################################################################
output_file=[${output_file}]
ts=[${ts}]
ip=[${ip}]

EOF

command="nslookup ${ip}"
{
    cat<<EOF
ts=[${ts}]
command=[${command}]
EOF
    ${command}
} | tee ${output_file}
