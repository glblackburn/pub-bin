#!/usr/bin/env bash
set -euET -o pipefail

script_name=$(basename $0)
script_dir=$(dirname $0)

################################################################################
# CLI Parameters
################################################################################

################################################################################
# default values
################################################################################
ts=`date +%Y-%m-%d_%H%M%S`
output_file=${script_name%.*}_${ts}.txt

################################################################################
# show command usage
################################################################################
function usage {
    message=${1:-}
    if [ ! -z "${message}" ] ; then
	echo "Message: ${message}"
    fi
    cat<<EOF
Usage: ${script_name}

Record system uptime information.

Options
  -h               : Display this help message.

Example:
$ ${script_name}
EOF
}

################################################################################
# get command line options
################################################################################
while getopts ":h" opt; do
    case ${opt} in
	h )
            usage
            exit 0
            ;;
	\? )
            usage "Invalid Option: -$OPTARG"
            exit 1
            ;;
    esac
done
shift $((OPTIND -1))

################################################################################
# functions
################################################################################

################################################################################
# main script logic
################################################################################

command="uptime"
{
    cat<<EOF
================================================================================
ts=[${ts}]
command=[${command}]
output_file=[${output_file}]
================================================================================
EOF
    ${command}
    cat<<EOF
================================================================================
ts=[${ts}]
command=[${command}]
output_file=[${output_file}]
================================================================================
EOF
} | tee ${output_file}
