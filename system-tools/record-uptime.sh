#!/usr/bin/env bash
set -euET -o pipefail

script_name=$(basename $0)
script_dir=$(dirname $0)

################################################################################
# default values
################################################################################
ts=`date +%Y-%m-%d_%H%M%S`

################################################################################
# get command line options
################################################################################

################################################################################
# main script logic
################################################################################
output_file=${script_name%.*}_${ts}.txt

cat<<EOF
################################################################################
# Debug info
################################################################################
output_file=[${output_file}]

EOF

command="uptime"
{
    cat<<EOF
================================================================================
ts=[${ts}]
command=[${command}]
output_file=[${output_file}]
================================================================================
EOF
    ${command}
    cat<<EOF
================================================================================
ts=[${ts}]
command=[${command}]
output_file=[${output_file}]
================================================================================
EOF
} | tee ${output_file}
